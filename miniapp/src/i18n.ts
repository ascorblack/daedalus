function fromUrl(): Lang | null {
  try {
    const raw = new URLSearchParams(window.location.search).get("lang");
    return raw === "ru" || raw === "en" ? raw : null;
  } catch {
    return null;
  }
}

function stored(): Lang | null {
  try {
    const raw = localStorage.getItem(STORE);
    return raw === "ru" || raw === "en" ? raw : null;
  } catch {
    return null; // private mode
  }
}

function fromBrowser(): Lang {
  const tags = [navigator.language, ...(navigator.languages ?? [])];
  return tags.some((tag) => (tag ?? "").toLowerCase().startsWith("ru")) ? "ru" : "en";
}

// A language named in the URL is a choice too: the launcher opens the app in the language its own
// window is in, and the reader should not have to make it twice. It is kept and then taken out of
// the address, so that it settles the question once instead of overriding the reader on every
// visit — and so that a link copied out of the bar carries no answer with it.
let current: Lang = fromUrl() ?? stored() ?? fromBrowser();
if (fromUrl()) {
  remember(current);
  stripUrl();
}

/** Take `lang` out of the address without reloading or adding to the history. */
function stripUrl(): void {
  try {
    const url = new URL(window.location.href);
    url.searchParams.delete("lang");
    window.history.replaceState(window.history.state, "", url.pathname + url.search + url.hash);
  } catch {
    /* no history to speak of */
  }
}

const listeners = new Set<() => void>();

function remember(next: Lang): void {
  try {
    localStorage.setItem(STORE, next);
  } catch {
    /* private mode */
  }
}

export function lang(): Lang {
  return current;
}

/** The Intl tag of the language in use, for every date, number and sum on the screen. */
export function locale(): string {
  return LOCALES[current];
}

export function setLang(next: Lang): void {
  if (next === current) return;
  current = next;
  remember(next);
  markDocument();
  for (const fire of listeners) fire();
}

/** Tell the page which language it is in, so the browser hyphenates and reads it correctly. */
function markDocument(): void {
  if (typeof document !== "undefined") document.documentElement.lang = current;
}

function fill(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/** One string, in the current language; `{name}` holes filled from `vars`. An unknown key shows itself in brackets. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const entry = DICT[key];
  if (!entry) return `[${key}]`;
  return fill(entry[current] ?? entry.en, vars);
}

/**
 * A count and the noun that goes with it: `plural("agents.count", 3)` → "3 агента".
 *
 * The forms live in the table separated by `|` — two in English (one, many), three in Russian (one,
 * a few, many) — because Russian picks by the last digit and not by "is it 1". `{n}` is filled with
 * the number, formatted in the reader's locale.
 */
export function plural(key: string, n: number, vars?: Record<string, string | number>): string {
  const entry = DICT[key];
  if (!entry) return `[${key}]`;
  const forms = (entry[current] ?? entry.en).split("|");
  const index = current === "ru" ? ruForm(n) : n === 1 ? 0 : 1;
  return fill(forms[Math.min(index, forms.length - 1)], { n: num(n), ...vars });
}

/** Russian picks by the last digit: 1 год, 2 года, 5 лет — and the teens are all "many". */
function ruForm(n: number): number {
  const abs = Math.abs(Math.round(n));
  const ten = abs % 10;
  const hundred = abs % 100;
  if (ten === 1 && hundred !== 11) return 0;
  if (ten >= 2 && ten <= 4 && (hundred < 12 || hundred > 14)) return 1;
  return 2;
}

/** A number as the reader's language writes it: 1,200 in English, 1 200 in Russian. */
export function num(n: number): string {
  return n.toLocaleString(locale());
}

/** The current language, and re-render when it changes. Returns the setter too, for a picker. */
export function useLang(): [Lang, (next: Lang) => void] {
  const [value, setValue] = useState(current);
  useEffect(() => {
    const fire = () => setValue(current);
    listeners.add(fire);
    fire();
    return () => {
      listeners.delete(fire);
    };
  }, []);
  return [value, setLang];
}

